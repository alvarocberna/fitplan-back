// Busca un grupo/subcategoria en FOOD_GROUP_PORTIONS. Lanza si no existe: significaría un
// error de programación (grupo/subcategoria mal escrito), no un caso de datos de usuario a manejar.
export function findFoodGroup(group: string, subcategory: string | null) {
    const found = FOOD_GROUP_PORTIONS.find(
        (g) => g.group === group && g.subcategory === subcategory,
    );
    if (!found) {
        throw new Error(`Grupo de alimentos no encontrado: ${group}/${subcategory}`);
    }
    return found;
}
